"""SkillTracker AI - interview page (Streamlit): setup, classic mode, avatar room, report."""
import hashlib
from datetime import datetime, timedelta

import streamlit as st

import config
from core import conversation, recordings, scoring
from core import database as db
from core.avatar_room import interview_room
from core.charts import gauge, radar
from core.proctor import proctor_monitor
from core.speech import text_to_speech, transcribe_audio, transcribe_media
from core.theme import plot_in
from core.ui import card, chips, get_engine, hero, setup_page, stepper

user = setup_page("SkillTracker AI", "🎙️")
engine = get_engine()
S = st.session_state

CUSTOM = "✏️ Custom skill"
DEFAULTS = {"stage": "setup", "interview_id": None, "cfg": {}, "q_no": 1, "current_q": None,
            "feedback": None, "results": [], "asked": [], "last_overall": None,
            "spoken_q": 0, "audio_hash": None, "summary": None, "celebrated": False,
            "turn": 0, "say": "", "record": True, "last_turn_done": None, "retries": 0, "closing": False,
            "room_error": None, "violations": 0, "violation_ids": []}
for k, v in DEFAULTS.items():
    S.setdefault(k, v)
S.setdefault("skill_choice", None)


def reset_interview():
    for k, v in DEFAULTS.items():
        S[k] = type(v)() if isinstance(v, (list, dict)) else v


def pick_skill(name: str):  # button callback
    S["skill_choice"] = name


def first_name() -> str:
    return (user["full_name"] or user["username"]).split()[0].title()


# ============================================================================ SETUP
def render_setup():
    hero(f"👋 Welcome, {first_name()}!", "Pick a skill, answer AI-generated questions out loud, and watch your progress grow.")
    stepper(0)

    iv = db.get_interviews_df(user["id"])
    prof = db.get_proficiency_df(user["id"])
    pmap = dict(zip(prof["skill"], prof["proficiency"]))
    week = int((iv["started_at"] > datetime.now() - timedelta(days=7)).sum()) if len(iv) else 0
    c1, c2, c3, c4 = st.columns(4)
    c1.metric("Interviews done", len(iv))
    c2.metric("Average score", f"{iv['overall_score'].mean():.1f}" if len(iv) else "–")
    c3.metric("Best skill", prof.sort_values("proficiency").iloc[-1]["skill"] if len(prof) else "–")
    c4.metric("Sessions this week", week)

    # ---- 1. skill cards
    st.markdown("### 🎯 1 · Choose a skill")
    skills = list(engine.bank.keys()) + [CUSTOM]
    if S.skill_choice not in skills:
        S["skill_choice"] = skills[0]
    if len(prof):
        weakest = prof.sort_values("proficiency").iloc[0]
        st.button(f"🎯 Practise my weakest skill: {weakest['skill']} ({weakest['proficiency']:.0f}/100)",
                  on_click=pick_skill, args=(weakest["skill"],))
    cols = st.columns(3)
    for i, name in enumerate(skills):
        chosen = S.skill_choice == name
        with cols[i % 3]:
            with st.container(border=True):
                emoji = config.SKILL_EMOJI.get(name, "✏️" if name == CUSTOM else "🎯")
                st.markdown(f'<span class="skill-emoji">{emoji}</span>&nbsp; **{name.replace("✏️ ", "")}**',
                            unsafe_allow_html=True)
                if name in pmap:
                    st.progress(min(1.0, pmap[name] / 100),
                                text=f"{pmap[name]:.0f}/100 · {scoring.level_for(pmap[name])}")
                else:
                    st.caption("Any topic you type, generated by AI" if name == CUSTOM else "Not attempted yet")
                st.button("✓ Selected" if chosen else "Select", key=f"pick_{i}", on_click=pick_skill, args=(name,),
                          type="primary" if chosen else "secondary")
    skill = S.skill_choice
    if skill == CUSTOM:
        skill = st.text_input("Type any skill (e.g. React, Docker, Excel, Public Speaking)", key="custom_skill").strip()
        if not engine.online:
            st.caption("Custom skills work best with a Gemini API key; offline mode uses generic questions.")

    # ---- 2. configure
    st.markdown("### ⚙️ 2 · Configure")
    mode_label = st.segmented_control("Interview style", ["🧑‍💼 Avatar video interview", "🎤 Classic (mic only)"],
                                      default="🧑‍💼 Avatar video interview", key="mode_pick") or "🎤 Classic (mic only)"
    avatar_mode = mode_label.startswith("🧑")
    cc1, cc2 = st.columns(2)
    with cc1:
        difficulty = st.segmented_control("Starting difficulty", config.DIFFICULTIES, default="Intermediate",
                                          key="diff") or "Intermediate"
    with cc2:
        total = st.slider("Number of questions", 3, 10, 5)
    if avatar_mode:
        st.caption(f"{config.AVATAR_NAME}, your AI interviewer, speaks each question and listens to your answer through "
                   "your camera and microphone, like a video call. Works best in Chrome or Edge.")

    # ---- 3. rules and consent
    st.markdown("### 🛡️ 3 · Rules and consent")
    rules_ok = True
    if config.PROCTORING_ENABLED:
        card(f"<h4>⚠️ Interview rules</h4><ul>"
             f"<li>Stay on this tab and window for the whole interview.</li>"
             f"<li>Switching tabs, minimising the browser or clicking into another app counts as a "
             f"<b>window violation</b>.</li>"
             f"<li>After <b>{config.MAX_VIOLATIONS} violations</b> the interview <b>ends automatically</b> and is not scored.</li>"
             f"<li>Violations are logged and visible to administrators.</li></ul>", "rules")
        rules_ok = st.checkbox(f"I understand the interview rules, including the {config.MAX_VIOLATIONS}-violation limit.")
    consent = True
    if avatar_mode:
        consent = st.checkbox("I consent to my camera and microphone being recorded during this interview. Recordings "
                              "are stored on this server and can be viewed by me and by administrators.")

    ready = bool(skill) and rules_ok and consent
    if st.button("▶️ Start interview", type="primary", disabled=not ready):
        reset_interview()
        S.cfg = {"skill": skill, "difficulty": difficulty, "total": total, "mode": "avatar" if avatar_mode else "classic"}
        S.interview_id = db.create_interview(user["id"], skill, difficulty, total, ai_mode=engine.mode)
        S.stage = "interview"
        st.rerun()
    if not ready:
        st.caption("Select a skill and tick the boxes above to start.")


# ================================================================ PROCTORING
def check_violations():
    """Read window-violation events from the browser, count them server-side and end the interview at the limit."""
    if not config.PROCTORING_ENABLED or S.closing:
        return
    ev = proctor_monitor(S.violations, config.MAX_VIOLATIONS, key="proctor")
    if ev and ev.get("type") == "violation" and ev.get("id") not in S.violation_ids:
        S.violation_ids.append(ev["id"])
        S.violations += 1
        db.add_violation(S.interview_id, user["id"], ev.get("kind", ""), ev.get("detail", ""))
        db.set_violation_count(S.interview_id, S.violations)
        if S.violations >= config.MAX_VIOLATIONS:
            terminate_interview()
            st.rerun()


def terminate_interview():
    """Automatic end after too many violations: stored, flagged, and excluded from scores and rankings."""
    cfg = S.cfg
    answered = len(S.results)
    partial = scoring.interview_score(r["overall"] for r in S.results) if answered else None
    text = (f"Interview ended automatically after {S.violations} window violations. "
            f"{answered} of {cfg['total']} questions had been answered.")
    db.finish_interview(S.interview_id, None, text, end_reason="violations", violations=S.violations)
    S.summary = {"terminated": True, "summary": text, "overall": partial, "answered": answered}
    S.stage = "result"


def status_bar():
    cfg = S.cfg
    items = [(f"{config.SKILL_EMOJI.get(cfg['skill'], '🎯')} {cfg['skill']}", ""), (cfg["difficulty"], ""),
             (f"Question {min(S.q_no, cfg['total'])} of {cfg['total']}", "")]
    if config.PROCTORING_ENABLED:
        left = config.MAX_VIOLATIONS - S.violations
        kind = "ok" if S.violations == 0 else ("bad" if left <= 1 else "warn")
        items.append((f"🛡️ Violations {S.violations}/{config.MAX_VIOLATIONS}", kind))
    chips(items)
    if S.violations:
        st.error(f"⚠️ {S.violations} window violation(s) recorded. Leaving the interview window "
                 f"{config.MAX_VIOLATIONS - S.violations} more time(s) will end the interview automatically.")


# ============================================================== CLASSIC INTERVIEW
def render_interview():
    check_violations()
    if S.cfg.get("mode") == "avatar":
        return render_room()
    cfg, q_no = S.cfg, S.q_no
    total = cfg["total"]

    if S.current_q is None:
        with st.spinner("🤖 The AI interviewer is preparing your next question…"):
            S.current_q = engine.generate_question(cfg["skill"], cfg["difficulty"], q_no, total, S.asked, S.last_overall)
            S.asked.append(S.current_q["question"])
    q = S.current_q

    stepper(2)
    status_bar()
    st.progress((q_no - 1 + (1 if S.feedback else 0)) / total, text=f"Question {q_no} of {total}")
    left, right = st.columns([2, 1], gap="large")

    with left:
        st.markdown(f'<div class="qcard">{q["question"]}</div>', unsafe_allow_html=True)
        if S.get("tts", True):
            audio = text_to_speech(q["question"])
            if audio:
                st.audio(audio, format="audio/mp3", autoplay=(S.spoken_q != q_no))
                S.spoken_q = q_no
        if S.feedback is None:
            render_answer_input(q)
        else:
            render_feedback(S.feedback)

    with right:
        render_side_panel(q)


def render_side_panel(q=None):
    st.markdown("#### 📈 Live session")
    if S.results:
        st.line_chart([r["overall"] for r in S.results], height=170)
        st.metric("Running average", f"{scoring.interview_score(r['overall'] for r in S.results):.1f}/100")
    else:
        st.caption("Your scores will appear here as you answer.")
    if q is not None:
        with st.expander("💡 Need a hint?"):
            topics = q.get("expected_topics") or []
            if topics:
                st.write(f"A strong answer covers about **{len(topics)}** key ideas. Think about: **{topics[0]}**.")
            else:
                st.write("Define the concept, explain how it works, then give a real example.")
    if S.results and not S.closing and st.button("⏹️ Finish early"):
        finish_interview()
        st.rerun()


def render_answer_input(q):
    q_no = S.q_no
    rec = st.audio_input("🎤 Click the mic, speak your answer, then click stop", key=f"audio_{q_no}")
    if rec is not None:
        data = rec.getvalue()
        h = hashlib.md5(data).hexdigest()
        if S.audio_hash != h:
            with st.spinner("📝 Transcribing your speech…"):
                text, err = transcribe_audio(data, S.get("speech_lang", "en-US"))
            S.audio_hash = h
            if err:
                st.warning(err)
            else:
                S[f"ta_{q_no}"] = text
                S[f"mode_{q_no}"] = "voice"

    answer = st.text_area("Transcript: edit if needed, or just type your answer", key=f"ta_{q_no}", height=140)
    if answer.strip():
        st.caption(f"{len(answer.split())} words")

    c1, c2, _ = st.columns([1, 1, 3])
    if c1.button("✅ Submit answer", type="primary"):
        if not answer.strip():
            st.warning("Please record or type an answer first (or use Skip).")
        else:
            process_answer(q, answer.strip(), S.get(f"mode_{q_no}", "typed"))
    if c2.button("⏭️ Skip"):
        process_answer(q, "", "skipped")


def process_answer(q, answer, mode):
    cfg = S.cfg
    with st.spinner("🧠 AI is evaluating your answer…"):
        ev = engine.evaluate_answer(cfg["skill"], cfg["difficulty"], q["question"], answer, q["expected_topics"])
    overall = scoring.compute_overall(ev)
    fillers, words = scoring.filler_stats(answer)
    rubric = {k: ev[k] for k in config.SCORE_WEIGHTS}
    db.save_answer(S.interview_id, S.q_no, q["question"], answer, mode, rubric, overall, fillers, words,
                   ev["feedback"], ev["strengths"], ev["improvements"])
    S.last_overall = overall
    S.feedback = {**ev, "overall": overall, "fillers": fillers, "words": words}
    S.results.append({"question": q["question"], "overall": overall, "improvements": ev["improvements"],
                      "answer": answer, **rubric})
    st.rerun()


def render_feedback(fb):
    st.markdown("---")
    g, d = st.columns([1, 2])
    plot_in(g, gauge(fb["overall"], "Answer score"), key=f"g_{S.q_no}")
    with d:
        for label in ("accuracy", "depth", "clarity", "relevance"):
            st.progress(fb[label] / 10, text=f"{label.title()}: {fb[label]}/10")
        st.write(fb["feedback"])
    c1, c2 = st.columns(2)
    if fb["strengths"]:
        c1.success("**Strengths**\n\n" + "\n".join(f"- {s}" for s in fb["strengths"]))
    if fb["improvements"]:
        c2.warning("**To improve**\n\n" + "\n".join(f"- {s}" for s in fb["improvements"]))
    if fb.get("ideal_answer_hint"):
        st.info(f"💡 **A model answer includes:** {fb['ideal_answer_hint']}")
    st.caption(f"Speech metrics: {fb['words']} words · {fb['fillers']} filler word(s)")

    last = S.q_no >= S.cfg["total"]
    if st.button("🏁 Finish interview" if last else "➡️ Next question", type="primary"):
        if last:
            finish_interview()
        else:
            S.q_no += 1
            S.current_q = None
            S.feedback = None
            S.audio_hash = None
        st.rerun()


# ================================================================== AVATAR ROOM
def render_room():
    cfg = S.cfg
    total = cfg["total"]
    if S.current_q is None and not S.closing:
        with st.spinner(f"{config.AVATAR_NAME} is preparing your first question…"):
            S.current_q = engine.generate_question(cfg["skill"], cfg["difficulty"], S.q_no, total, S.asked, S.last_overall)
            S.asked.append(S.current_q["question"])
        S.turn = 1
        S.say = conversation.greeting(first_name(), config.AVATAR_NAME, cfg["skill"], S.current_q["question"])
        S.record = True

    stepper(2)
    status_bar()
    answered = len(S.results)
    st.progress(min(1.0, answered / total), text=f"{answered} of {total} questions answered")

    left, right = st.columns([3, 1], gap="large")
    turn_id = f"{S.interview_id}-{S.turn}"
    with left:
        val = interview_room(S.say, turn_id, S.record, lang=S.get("speech_lang", "en-US"))
        if S.closing:
            if st.button("📋 View my report", type="primary"):
                finish_interview()
                st.rerun()
        else:
            with st.expander("⌨️ Camera or microphone not working? Type your answer instead"):
                typed = st.text_area("Your answer", key=f"typed_{S.turn}", height=110)
                if st.button("Submit typed answer") and typed.strip():
                    S.last_turn_done = turn_id
                    handle_answer(typed.strip(), None, None, "video/webm", "audio/webm", 0.0, "typed")
        if S.feedback:
            render_last_feedback(S.feedback)

    with right:
        render_side_panel()
        if S.room_error:
            st.error(f"Camera/microphone problem: {S.room_error}")
            if st.button("Switch to classic mode"):
                S.cfg["mode"] = "classic"
                S.room_error = None
                st.rerun()
        st.caption("Tip: speak naturally. I'll move on when you pause for a few seconds, or press **Done answering**.")

    if val and val.get("type") == "error":
        if S.room_error != val.get("error"):
            S.room_error = val.get("error")
            st.rerun()
    elif val and val.get("type") == "answer" and val.get("id") == turn_id and S.last_turn_done != turn_id:
        S.last_turn_done = turn_id
        handle_answer(val.get("transcript", "").strip(), recordings.decode_b64(val.get("video_b64")),
                      recordings.decode_b64(val.get("audio_b64")),
                      val.get("v_mime") or "video/webm", val.get("a_mime") or "audio/webm",
                      float(val.get("duration") or 0), "video")


def handle_answer(transcript, video, audio, v_mime, a_mime, duration, mode):
    """Transcribe if needed, score, save (answer + recording), then let the avatar react and ask the next question."""
    cfg, q = S.cfg, S.current_q
    if not transcript and audio:
        with st.spinner("Transcribing your answer…"):
            transcript, _err = transcribe_media(audio, S.get("speech_lang", "en-US"))
        transcript = (transcript or "").strip()
    if not transcript:
        S.retries += 1
        S.turn += 1
        if S.retries <= 1:                       # ask again once, like a person would
            S.say = conversation.retry_prompt(q["question"])
            S.record = True
            st.rerun()
        transcript, mode = "", "skipped"         # second miss: record as skipped and move on
    S.retries = 0

    with st.spinner(f"{config.AVATAR_NAME} is thinking…"):
        ev = engine.evaluate_answer(cfg["skill"], cfg["difficulty"], q["question"], transcript, q["expected_topics"])
        overall = scoring.compute_overall(ev)
        fillers, words = scoring.filler_stats(transcript)
        rubric = {k: ev[k] for k in config.SCORE_WEIGHTS}
        db.save_answer(S.interview_id, S.q_no, q["question"], transcript, mode, rubric, overall, fillers, words,
                       ev["feedback"], ev["strengths"], ev["improvements"])
        recordings.store_recording(user["id"], S.interview_id, S.q_no, q["question"], transcript, video, audio,
                                   v_mime, a_mime, duration)
        S.last_overall = overall
        S.feedback = {**ev, "overall": overall, "fillers": fillers, "words": words, "q_no": S.q_no}
        S.results.append({"question": q["question"], "overall": overall, "improvements": ev["improvements"],
                          "answer": transcript, **rubric})
        react = conversation.reaction(overall, ev["feedback"], use_feedback=ev.get("source") == "gemini")
        if S.q_no >= cfg["total"]:
            S.closing = True
            S.say, S.record = conversation.closing(react, first_name()), False
        else:
            S.q_no += 1
            S.current_q = engine.generate_question(cfg["skill"], cfg["difficulty"], S.q_no, cfg["total"],
                                                   S.asked, S.last_overall)
            S.asked.append(S.current_q["question"])
            S.say = conversation.next_turn(react, S.current_q["question"], S.q_no, cfg["total"])
            S.record = True
    S.turn += 1
    st.rerun()


def render_last_feedback(fb):
    with st.expander(f"📝 Feedback on question {fb.get('q_no', '')}: {fb['overall']}/100", expanded=True):
        cols = st.columns(4)
        for col, label in zip(cols, ("accuracy", "depth", "clarity", "relevance")):
            col.metric(label.title(), f"{fb[label]}/10")
        st.write(fb["feedback"])
        c1, c2 = st.columns(2)
        if fb["strengths"]:
            c1.success("**Strengths**\n\n" + "\n".join(f"- {x}" for x in fb["strengths"]))
        if fb["improvements"]:
            c2.warning("**To improve**\n\n" + "\n".join(f"- {x}" for x in fb["improvements"]))
        st.caption(f"{fb['words']} words · {fb['fillers']} filler word(s)")


# ===================================================================== FINISH
def finish_interview():
    cfg = S.cfg
    overall = scoring.interview_score(r["overall"] for r in S.results)
    with st.spinner("📋 Preparing your final report…"):
        summary = engine.final_summary(cfg["skill"], cfg["difficulty"], overall, S.results)
    S.summary = {**summary, "overall": overall}
    db.finish_interview(S.interview_id, overall, summary["summary"],
                        end_reason="completed" if len(S.results) >= cfg["total"] else "early", violations=S.violations)
    old = db.get_proficiency(user["id"], cfg["skill"])
    new_prof = scoring.update_proficiency(old["proficiency"] if old else None, overall)
    db.upsert_proficiency(user["id"], cfg["skill"], new_prof, (old["sessions"] if old else 0) + 1)
    S.summary["proficiency"] = new_prof
    S.summary["previous"] = old["proficiency"] if old else None
    S.stage = "result"


def report_markdown() -> str:
    sm, cfg = S.summary, S.cfg
    lines = [f"# Interview report - {cfg['skill']}", f"Candidate: {user['full_name'] or user['username']}",
             f"Date: {datetime.now():%Y-%m-%d %H:%M}", f"Score: {sm['overall']}/100 ({scoring.level_for(sm['overall'])})",
             f"Window violations: {S.violations}/{config.MAX_VIOLATIONS}",
             "", sm["summary"], "", "## Focus areas"] + [f"- {x}" for x in sm["focus_areas"]] + ["", "## Questions"]
    for i, r in enumerate(S.results, 1):
        lines += [f"### Q{i}. {r['question']} ({r['overall']}/100)", f"Answer: {r['answer'] or '(skipped)'}", ""]
    return "\n".join(lines)


# ===================================================================== RESULT
def render_terminated():
    sm, cfg = S.summary, S.cfg
    hero("⛔ Interview ended", f"{cfg['skill']} · stopped after {S.violations} window violations", danger=True)
    stepper(3)
    c1, c2, c3 = st.columns(3)
    c1.metric("Questions answered", f"{sm['answered']} of {cfg['total']}")
    c2.metric("Window violations", f"{S.violations}/{config.MAX_VIOLATIONS}")
    c3.metric("Score", "Not counted")
    st.error(sm["summary"])
    card("<h4>What happened?</h4><p>The interview window was left (tab switched, window minimised or another application "
         f"opened) {S.violations} times. To keep sessions fair, the interview was ended automatically. This attempt is "
         "not scored and does not change your skill level, but the answers given so far are saved and administrators "
         "can see the violation log.</p><p>You are welcome to start a new interview at any time.</p>")
    b1, b2, _ = st.columns([1, 1, 3])
    if b1.button("🔁 New interview", type="primary"):
        reset_interview()
        st.rerun()
    b2.page_link("pages/1_Dashboard.py", label="📊 Open dashboard")


def render_result():
    sm, cfg = S.summary, S.cfg
    if sm.get("terminated"):
        return render_terminated()
    if sm["overall"] >= 80 and not S.celebrated:
        st.balloons()
        S.celebrated = True
    hero("📋 Interview report", f"{cfg['skill']} · {cfg['difficulty']}")
    stepper(3)
    if S.violations:
        chips([(f"🛡️ Window violations: {S.violations}/{config.MAX_VIOLATIONS}", "warn")])
    g, r = st.columns(2)
    plot_in(g, gauge(sm["overall"], f"Score · {scoring.level_for(sm['overall'])}", 260), key="res_g")
    labels = ["Accuracy", "Depth", "Clarity", "Relevance"]
    vals = [sum(x[k.lower()] for x in S.results) / max(1, len(S.results)) for k in labels]
    plot_in(r, radar(labels, vals, 10, 260, "Rubric"), key="res_r")

    prev = sm.get("previous")
    st.metric(f"{cfg['skill']} proficiency", f"{sm['proficiency']:.0f}/100",
              None if prev is None else f"{sm['proficiency'] - prev:+.1f} since last time")
    st.write(sm["summary"])
    c1, c2 = st.columns(2)
    c1.success("**Top strengths**\n\n" + "\n".join(f"- {s}" for s in sm["top_strengths"]))
    c2.warning("**Focus areas**\n\n" + "\n".join(f"- {s}" for s in sm["focus_areas"]))
    if sm["resources"]:
        st.info("**Suggested study topics**\n\n" + "\n".join(f"- {s}" for s in sm["resources"]))

    with st.expander("Question breakdown", expanded=False):
        for i, x in enumerate(S.results, 1):
            st.markdown(f"**Q{i}. {x['question']}** — {x['overall']}/100")
            st.caption(x["answer"] or "_skipped_")

    b1, b2, b3 = st.columns(3)
    if b1.button("🔁 New interview", type="primary"):
        reset_interview()
